# -*- coding: utf-8 -*-
"""生成测试用知识库文档。

每个业务域一个知识库，每个知识库 20 篇文档，每篇约 5000 字。
输出目录：data/knowledge-bases/{DOMAIN_CODE}/{文档编号}_{主题}.md

用法：python scripts/generate_test_kb.py
"""

from __future__ import annotations

import re
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
OUTPUT_DIR = ROOT / "data" / "knowledge-bases"


def build_document(domain: str, theme: dict, related_titles: list[str] | None = None) -> str:
    """根据主题数据展开一篇约 5000 字的制度文档。"""
    title = theme["title"]
    no = theme["no"]
    dept = theme["dept"]
    eff_date = theme.get("date", "2026-01-01")
    purpose = theme["purpose"]
    basis = theme.get("basis", [])
    scope = theme.get("scope", "本部门全体员工")
    terms = theme.get("terms", [])
    rules = theme.get("rules", [])
    process = theme.get("process", [])
    standards = theme.get("standards", [])
    faqs = theme.get("faqs", [])
    cases = theme.get("cases", [])
    notes = theme.get("notes", [])
    related_titles = related_titles or []
    # 去掉制度类后缀，用于正文拼接，避免"管理规定管理工作"式重复。
    short = re.sub(
        r"(管理规定|管理办法|管理制度|管理规范|操作指南|使用说明|使用指南|"
        r"管理规定|管理办法|规定|办法|制度|指南|说明|指引|规范|手册)$",
        "",
        title,
    )

    lines: list[str] = []
    add = lines.append

    add(f"# {title}")
    add("")
    add(f"> 文档编号：{no}　生效日期：{eff_date}　责任部门：{dept}")
    add("> 密级：内部资料　版本：V1.0　适用范围：{scope}".format(scope=scope))
    add("")

    # 1. 总则
    add("## 1. 总则")
    add("")
    add("### 1.1 目的")
    add("")
    add(f"为规范公司{short}管理工作，明确各部门职责与办理标准，保障业务有序开展，"
        f"结合公司实际情况，特制定本规定。{purpose}")
    add("")
    add("### 1.2 制定依据")
    add("")
    add("本规定依据国家相关法律法规、行业规范以及公司内部管理制度制定，主要包括：")
    for item in basis:
        add(f"- {item}")
    add("")
    add("### 1.3 适用范围")
    add("")
    add(f"本规定适用于公司{scope}，以及涉及{short}相关事项的全体员工和相关部门。")
    add("")
    add("### 1.4 基本原则")
    add("")
    add(f"公司{short}管理遵循以下原则：一是依法合规，严格遵守法律法规和公司制度；"
        "二是真实有效，所有申报材料必须真实、完整、可追溯；"
        "三是分级审批，按照事项金额和重要程度实行分级授权；"
        "四是公开透明，办理流程、标准和结果在内部公开接受监督。")
    add("")

    # 2. 术语定义
    if terms:
        add("## 2. 术语与定义")
        add("")
        for term, desc in terms:
            add(f"- **{term}**：{desc}")
        add("")

    # 3. 职责分工
    add("## 3. 职责分工")
    add("")
    add(f"### 3.1 归口管理部门")
    add("")
    add(f"{dept}是{title}工作的归口管理部门，主要职责包括：制定和完善相关管理制度；"
        "审核各项申报事项的真实性与合规性；组织相关评审和审批；"
        "对办理过程进行监督检查；定期汇总分析数据并向管理层报告。")
    add("")
    add("### 3.2 相关部门职责")
    add("")
    add("涉及的相关部门按照业务归口原则各司其职：业务发起部门负责事项的申报与资料准备，"
        "对所提交材料的真实性负责；财务部门负责涉及资金事项的核算与支付；"
        "法务部门负责涉及合同与法律风险事项的审核；"
        "行政综合部门负责档案归档与后勤保障。各部门应当指定专人作为对接人。")
    add("")

    # 4. 管理细则
    add("## 4. 管理细则")
    add("")
    for idx, rule in enumerate(rules, start=1):
        if isinstance(rule, str):
            add(f"### 4.{idx} {rule[:14]}")
            add("")
            add(rule)
            add("")
        else:
            name, content = rule
            add(f"### 4.{idx} {name}")
            add("")
            add(content)
            add("")

    # 5. 办理流程
    if process:
        add("## 5. 办理流程")
        add("")
        add("| 步骤 | 环节 | 办理说明 | 时限 |")
        add("|------|------|----------|------|")
        for step, name, desc, limit in process:
            add(f"| {step} | {name} | {desc} | {limit} |")
        add("")
        add("上述流程中，各环节办理人应当及时处理并如实记录办理意见；"
            "超时未处理的，系统自动提醒上级审批人。任何环节不得无故拖延或拒绝办理。")
        add("")

    # 6. 标准与限额
    if standards:
        add("## 6. 标准与限额")
        add("")
        add("| 项目 | 标准 | 说明 |")
        add("|------|------|------|")
        for item, standard, note in standards:
            add(f"| {item} | {standard} | {note} |")
        add("")
        add("以上标准为公司统一执行口径，具体以公司最新发布的制度文件为准。"
            "如遇政策调整或市场变化，由归口管理部门提出修订建议，经审批后执行。")
        add("")
        add("> 注意：正文条款中涉及的数值型标准，以本章「标准与限额」表格为准；"
            "两者不一致时，以本章表格为执行口径。")
        add("")

    # 7. 常见问题
    if faqs:
        add("## 7. 常见问题")
        add("")
        for q, a in faqs:
            add(f"### Q：{q}")
            add("")
            add(f"答：{a}")
            add("")

    # 8. 案例说明
    if cases:
        add("## 8. 案例说明")
        add("")
        for case_name, detail in cases:
            add(f"### 案例：{case_name}")
            add("")
            add(detail)
            add("")

    # 9. 监督检查与违规处理
    add("## 9. 监督检查与违规处理")
    add("")
    add(f"{dept}会同审计部门定期对{title}执行情况进行检查，检查内容包括："
        "申报资料的真实性与完整性、审批程序的合规性、标准执行的准确性、"
        "办理时限的及时性等。对检查中发现的问题，责令限期整改并跟踪复核。")
    add("")
    add("有下列情形之一的，视情节轻重给予通报批评、责令改正、追回相关款项、"
        "扣减绩效直至解除劳动合同等处理，涉嫌违法的移送司法机关："
        "一是提供虚假材料或隐瞒重要事实的；二是未经审批擅自办理的；"
        "三是超标准、超范围办理的；四是利用职务便利谋取私利的；"
        "五是其他违反本规定的情形。")
    add("")

    # 10. 附则
    add("## 10. 附则")
    add("")
    add("本规定由{dept}负责解释和修订。本规定自发布之日起施行，"
        "原有相关规定与本规定不一致的，以本规定为准。".format(dept=dept))
    add("")
    add("本规定修订时，应当充分征求相关部门意见，经公司办公会审议通过后发布。"
        "本规定未尽事宜，参照公司其他相关管理制度执行。")
    add("")
    add("### 通用执行说明")
    add("")
    add(f"本规定各条款在执行过程中如遇特殊情况，由归口管理部门{dept}会同相关部门"
        "研究提出处理意见，报公司分管领导批准后执行，并在后续制度修订时予以明确。"
        "特殊情况处理应当书面留痕，作为后续同类事项的执行参考。")
    add("")

    if notes:
        add("### 补充说明")
        add("")
        for note in notes:
            add(f"- {note}")
        add("")

    # 11. 相关制度衔接
    add("## 11. 相关制度衔接")
    add("")
    add(f"{title}与公司其他管理制度相互衔接、配套执行。"
        "在执行本规定时，应当同时遵循以下相关制度的要求：")
    add("")
    for related in related_titles:
        add(f"- 《{related}》")
    add("")
    add("当本规定与上述相关制度对同一事项的规定不一致时，"
        "按照「新规定优于旧规定、专门规定优于一般规定」的原则执行；"
        "无法判断适用顺序的，由归口管理部门会同相关部门研究确定，并报分管领导批准。"
        "各部门在执行过程中发现制度之间衔接存在冲突或空白的，"
        "应当及时向归口管理部门反馈，由归口管理部门牵头组织修订完善。")
    add("")

    # 12. 执行要点与常见误区
    add("## 12. 执行要点与常见误区")
    add("")
    add("### 12.1 执行要点")
    add("")
    rule_names = [r[0] if isinstance(r, tuple) else r[:14] for r in rules]
    add(f"根据本规定第4章的管理细则，{short}执行过程中应当重点把握以下要点：")
    add("")
    for idx, name in enumerate(rule_names[:8], start=1):
        add(f"{idx}. **{name}**：严格执行相关标准与程序，"
            "涉及金额、时限与审批权限的事项，以本规定及配套流程为准，"
            "不得擅自变通或口头承诺。")
    add("")
    add("同时应当建立过程记录，做到「事事有记录、件件可追溯」。"
        "归口管理部门定期抽查执行情况，对执行偏差及时纠正。")
    add("")
    add("### 12.2 常见误区")
    add("")
    add("在实际执行中，常见的理解与操作误区包括：")
    add("")
    add(f"- **误区一：认为{short}只要结果正确，过程手续可以事后补办。**"
        "事实上，本规定强调事前审批与过程留痕，事后补办须说明原因并经相关领导确认，"
        "频繁事后补办将被纳入合规检查重点。")
    add(f"- **误区二：认为标准是「建议值」，可以适当突破。**"
        "本规定所列标准与限额均为执行口径，突破标准须按审批权限提前报批，"
        "未经批准的超标支出不予认可。")
    add(f"- **误区三：认为{short}仅归口部门负责，其他部门无需关注。**"
        "各部门均为执行主体，负有申报、审核与监督的相应责任，"
        "归口管理部门负责统筹与督导。")
    add(f"- **误区四：认为历史做法可以延续，不关注制度更新。**"
        "制度修订后以最新版本为准，各部门应及时学习并向归口管理部门确认执行口径。")
    add("")

    # 13. 培训宣导与档案管理
    add("## 13. 培训宣导与档案管理")
    add("")
    add("### 13.1 培训宣导")
    add("")
    add(f"{dept}负责组织本规定的培训宣导工作。新员工入职培训纳入本规定相关内容，"
        "在职员工每年至少参加一次相关制度的集中学习。"
        "制度修订发布后，归口管理部门应当在一周内组织修订内容解读，"
        "确保相关人员知悉最新要求。培训完成情况纳入部门培训档案管理。")
    add("")
    add("### 13.2 档案管理")
    add("")
    add(f"{title}相关的申请、审批、票据、记录与台账等资料，"
        "按照公司档案管理制度的要求归档保存。归档资料应当真实、完整、清晰，"
        "电子档案与纸质档案保持一致。档案保管期限按照档案管理制度执行，"
        "到期鉴定后按规定销毁，涉密资料按照保密管理制度管理。")
    add("")

    # 14. 持续改进与考核
    add("## 14. 持续改进与考核")
    add("")
    add(f"归口管理部门{dept}应当定期对{short}执行情况进行总结分析，"
        "识别流程中的堵点、痛点与风险点，提出优化建议并推动制度修订。"
        "公司鼓励各部门与员工提出改进建议，经评估采纳的建议按照公司合理化建议制度给予奖励。")
    add("")
    add("本规定的执行情况纳入相关部门年度考核，考核内容包括制度执行的合规率、"
        "办理时效、资料完整性与监督检查整改情况等。"
        "对执行到位、表现突出的部门和个人给予表彰，对执行不力造成不良影响的依规处理。")
    add("")

    # 15. 情景问答与办理指引
    add("## 15. 情景问答与办理指引")
    add("")
    add("为便于理解与执行，以下结合日常办理中的典型情景给出指引说明。"
        "情景指引仅作参考，具体以本规定及相关制度正式文本为准。")
    add("")
    step_names = [s[1] for s in process] if process else []
    first_step = step_names[0] if step_names else "申请"
    last_step = step_names[-1] if step_names else "归档"
    add(f"### 情景一：首次办理{title}事项")
    add("")
    add(f"员工首次办理时，建议先阅读本规定，重点了解适用范围、标准与流程。"
        f"办理的第一步是{first_step}，由发起人按要求准备资料并提交；"
        f"后续依次经过{last_step}等环节。"
        "如对流程或标准存在疑问，可先向部门对接人或归口管理部门咨询，"
        "避免因资料不齐或标准理解偏差造成返工。")
    add("")
    add(f"### 情景二：{title}过程中遇到特殊情况")
    add("")
    add(f"当办理过程中出现本规定未明确涵盖的特殊情况时，"
        "不得擅自比照或变通执行，应当及时将情况书面反馈给{dept}，"
        "由归口管理部门会同相关部门研究处理意见，报分管领导批准后执行。"
        "处理意见应当记录存档，作为后续同类事项的参考口径。")
    add("")
    add("### 情景三：发现他人存在违规办理行为")
    add("")
    add(f"发现违反{short}规定的行为，任何员工均有权也有义务向归口管理部门或"
        "公司监督渠道反映。反映问题时尽量提供客观事实与相关材料，"
        "公司对反映人信息严格保密，严禁对反映人进行打击报复。"
        "经查实的违规行为按照本规定第9章及公司奖惩制度处理。")
    add("")
    add(f"### 情景四：对制度内容存在不同理解")
    add("")
    add(f"员工对{short}条款存在不同理解时，以归口管理部门{dept}的解释为准。"
        "如果解释涉及重大利益或与其他制度冲突，归口管理部门应当提请公司审议，"
        "必要时修订完善制度文本。制度解释与修订情况应当及时向全员公布。")
    add("")

    # 16. 责任矩阵与时限对照
    add("## 16. 责任矩阵与时限对照")
    add("")
    add("下表汇总本规定涉及的主要角色、职责与办理时限要求，便于对照执行与监督：")
    add("")
    add("| 角色 | 主要职责 | 关键时限 |")
    add("|------|----------|----------|")
    add(f"| 发起人 | 按要求准备资料并提交申请，对材料真实性负责 | {first_step}前完成准备 |")
    add(f"| 部门负责人 | 初审事项真实性与合规性 | 受理后1个工作日 |")
    add(f"| {dept} | 归口审核、标准把关与督导 | 受理后2个工作日 |")
    add("| 财务/法务等协审部门 | 涉及资金或法律事项的专业审核 | 受理后1个工作日 |")
    add(f"| 分管领导/总经理 | 按权限审批重大事项 | 受理后1个工作日 |")
    add(f"| 档案管理 | 资料归档与台账维护 | {last_step}后及时归档 |")
    add("")
    add("各环节责任人应当严格按照时限办理，因故无法按时完成的应当提前说明并交接。"
        "归口管理部门定期统计各环节办理时效，对超时情况进行提醒与通报。")
    add("")

    return "\n".join(lines)


def safe_filename(title: str) -> str:
    """将标题转为安全的文件名片段。"""
    return re.sub(r"[\\/:*?\"<>|\s]+", "-", title).strip("-")


def generate(domain: str, themes: list[dict]) -> list[tuple[Path, int]]:
    """生成一个域的全部文档，返回 (文件路径, 字数) 列表。"""
    out_dir = OUTPUT_DIR / domain
    out_dir.mkdir(parents=True, exist_ok=True)
    result = []
    for theme in themes:
        related_titles = [t["title"] for t in themes if t is not theme][:8]
        text = build_document(domain, theme, related_titles)
        path = out_dir / f"{theme['no']}_{safe_filename(theme['title'])}.md"
        path.write_text(text, encoding="utf-8")
        result.append((path, len(text)))
    return result


