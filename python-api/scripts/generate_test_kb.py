def main() -> None:
    total_files = 0
    total_chars = 0
    summary = []
    for domain, themes in ALL_THEMES.items():
        items = generate(domain, themes)
        total_files += len(items)
        chars = sum(c for _, c in items)
        total_chars += chars
        avg = chars // len(items)
        summary.append((domain, len(items), chars, avg))
        print(f"[{domain}] {len(items)} 篇, 共 {chars} 字, 平均 {avg} 字/篇")
    print(f"总计: {total_files} 篇, 共 {total_chars} 字")
    print(f"输出目录: {OUTPUT_DIR}")


if __name__ == "__main__":
    main()
